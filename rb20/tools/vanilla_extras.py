# ------------------------------------------------------------------ sfx/*.wav
def write_wavs(car_dir):
    sfx = os.path.join(car_dir, "sfx")
    count = 0
    for prefix, n, seed0 in (("backfire_", 11, 100), ("backfireEXT_", 9, 900)):
        for k in range(1, n + 1):
            rng = random.Random(seed0 + k)
            rate, dur = 22050, 0.10
            frames = int(rate * dur)
            buf = bytearray()
            for i in range(frames):
                env = math.exp(-i / (rate * 0.018))
                noise = rng.uniform(-1.0, 1.0)
                body = math.sin(2 * math.pi * (95 + 20 * k) * i / rate)
                s = int(32767 * 0.32 * env * (0.75 * noise + 0.25 * body))
                buf += struct.pack("<h", max(-32768, min(32767, s)))
            path = os.path.join(sfx, "%s%d.wav" % (prefix, k))
            os.makedirs(sfx, exist_ok=True)
            with wave.open(path, "wb") as f:
                f.setnchannels(1)
                f.setsampwidth(2)
                f.setframerate(rate)
                f.writeframes(bytes(buf))
            count += 1
    return count


# ----------------------------------------------------------------- extra ksanim
def extra_ksanims(car_dir):
    import features
    anim = os.path.join(car_dir, "animations")

    def frames(count, swing_deg):
        out = []
        for i in range(count):
            t = math.radians(-swing_deg + 2.0 * swing_deg * i / (count - 1))
            q = (0.0, 0.0, math.sin(t / 2.0), math.cos(t / 2.0))
            out.append((q, (0.0, 0.0, 0.0), (1.0, 1.0, 1.0)))
        return out

    # Driver shift gestures and the cockpit gear lever: vanilla v2 files with
    # original keyframes. The game uses them through driver3d.ini conventions.
    features.write_ksanim(os.path.join(anim, "shift.ksanim"),
                          "DRIVER:RIG_HAND_R", frames(21, 8.0))
    features.write_ksanim(os.path.join(anim, "car_shift.ksanim"),
                          "STEER_HR", frames(11, 3.0))
    return 2


# ----------------------------------------------------------------------- ui PNGs
def write_ui_extras(car_dir):
    try:
        from PIL import Image
    except ImportError:
        return
    ui = os.path.join(car_dir, "ui")
    badge = os.path.join(ui, "badge.png")
    if os.path.exists(badge):
        Image.open(badge).convert("RGBA").save(os.path.join(ui, "old_badge.png"))
        im = Image.open(badge).convert("RGB")
        im.thumbnail((128, 128))
        im.save(os.path.join(ui, "upgrade.png"))
    small = os.path.join(ui, "preview_small.png")
    if os.path.exists(small):
        Image.open(small).convert("RGB").save(os.path.join(ui, "dlc_preview.png"))


def apply(car_dir):
    data = os.path.join(car_dir, "data")
    write_knh(os.path.join(car_dir, "driver_base_pos.knh"))
    write_flames(car_dir)
    w(os.path.join(data, "flames.ini"), FLAMES_INI)
    w(os.path.join(data, "flame_presets.ini"), FLAME_PRESETS)
    write_ratios(car_dir)
    w(os.path.join(data, "wing_controller_speed.lut"), WING_SPEED_LUT)
    w(os.path.join(data, "wing_controller_brake.lut"), WING_BRAKE_LUT)
    w(os.path.join(data, "analog_instruments.ini"), ANALOG_INI)
    w(os.path.join(data, "analog_speed_curve.lut"), ANALOG_SPEED_LUT)
    w(os.path.join(car_dir, "skins", "default", "skin.ini"), SKIN_INI)
    nwav = write_wavs(car_dir)
    nks = extra_ksanims(car_dir)
    write_ui_extras(car_dir)
    print("  vanilla_extras: KNH, flames DDS/INI, ratios.rto, wing LUTs, "
          "analog dash, skin.ini, %d WAVs, %d ksanim, UI PNGs" % (nwav, nks))
