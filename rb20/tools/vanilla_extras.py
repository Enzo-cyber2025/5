# ------------------------------------------------------------------- ratios .rto
def write_ratios(car_dir):
    data = os.path.join(car_dir, "data")
    cp = configparser.ConfigParser(strict=False, inline_comment_prefixes=(";",))
    cp.optionxform = str
    cp.read(os.path.join(data, "drivetrain.ini"))
    gears = cp["GEARS"] if cp.has_section("GEARS") else {}
    vals = []
    for i in range(1, 9):
        try:
            vals.append(abs(float(gears.get("GEAR_%d" % i, "0"))))
        except ValueError:
            pass
    vals = [v for v in vals if v > 0]
    if not vals:
        vals = [2.6, 2.1, 1.8, 1.55, 1.36, 1.20, 1.08, 0.98]
    final = float(gears.get("FINAL", "3.10"))

    # Tooth-count notation of the vanilla .rto format, derived from our own
    # telemetry-fitted gearbox rather than copied from a Kunos car.
    def line(r):
        den = 30
        num = max(10, min(60, int(round(r * den))))
        return "%d//%d|%.2f" % (num, den, num / den)

    candidates = sorted(set(vals + [(vals[i] + vals[i + 1]) / 2.0
                                    for i in range(len(vals) - 1)]))
    lines = [line(r) for r in candidates]
    while len(lines) < 16:
        lines.append(line(max(candidates) * (1.0 + 0.06 * len(lines))))
    w(os.path.join(data, "ratios.rto"), "\n".join(lines[:16]) + "\n")
    w(os.path.join(data, "final.rto"),
      "".join(line(final * f) + "\n" for f in (0.90, 1.00, 1.10)))


