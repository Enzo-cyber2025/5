"""
vanilla_extras.py -- the remaining non-proprietary vanilla AC car files.

Everything here is ORIGINAL content generated by this build. No Kunos binary,
no FMOD bank, no third-party texture or sample is copied. Formats were derived
from vanilla examples (Kunos formula_k / ks_mazda_mx5_nd2) and from parsing
their on-disk layout:

  * driver_base_pos.knh : int32 nameLen + name + 16f matrix + int32 childCount,
                          recursively (the Kunos file parses exactly to EOF).
  * texture/flames/*.dds: uncompressed 32-bit A8R8G8B8 DDS (standard DirectX
                          header; vanilla AC loads it, no CSP shader needed).
  * *.ksanim            : vanilla v2, quat(x,y,z,w) + pos(3) + scale(3).
  * *.wav               : plain PCM RIFF, synthetic backfire bursts.
  * *.rto / *.lut       : plain-text vanilla ratio / lookup tables.

Nothing here requires CSP, Lua, data.acd, extended physics or RainFX.
"""
from __future__ import annotations

