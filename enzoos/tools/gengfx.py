def new_img(w, h):
    return [[(0xFF000000) for _ in range(w)] for _ in range(h)]

def px(img, x, y, c):
    if 0 <= x < len(img[0]) and 0 <= y < len(img):
        img[y][x] = c

def rect(img, x, y, w, h, c):
    for j in range(y, y + h):
        for i in range(x, x + w):
            px(img, i, j, c)

def lerp(a, b, t):
    return int(a + (b - a) * t)

def rgb(r, g, b):
    return 0xFF000000 | (r << 16) | (g << 8) | b

def make_logo():
    """Logo EnzoOS 64x64: quadrado arredondado com gradiente e 'E' cortado."""
    img = new_img(64, 64)
    # fundo com gradiente diagonal (azul profundo -> ciano)
    for y in range(64):
        for x in range(64):
            t = (x + y) / 126.0
            img[y][x] = rgb(lerp(13, 0, t), lerp(27, 178, t), lerp(62, 160, t))
    # cantos "arredondados" (recorte)
    for r in range(10):
        for k in range(10 - r):
            px(img, k, r, 0x00000000)
            px(img, 63 - k, r, 0x00000000)
            px(img, k, 63 - r, 0x00000000)
            px(img, 63 - k, 63 - r, 0x00000000)
    # brilho superior
    for y in range(6, 16):
        for x in range(10, 54):
            if img[y][x] != 0xFF000000:
                c = img[y][x]
                img[y][x] = 0xFF000000 | ((c & 0xFFFFFF) + 0x202020)
    # letra E branca (barras)
    rect(img, 18, 18, 8, 30, rgb(245, 250, 255))
    rect(img, 18, 18, 26, 7,  rgb(245, 250, 255))
    rect(img, 18, 30, 22, 6,  rgb(245, 250, 255))
    rect(img, 18, 41, 26, 7,  rgb(245, 250, 255))
    # acento ciano no E (marca)
    rect(img, 44, 18, 6, 30, rgb(0, 200, 160))
    rect(img, 38, 24, 6, 6,  rgb(0, 230, 180))
    return img

