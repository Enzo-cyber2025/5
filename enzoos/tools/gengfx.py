def emit_keymap():
    def table(which):
        t = [[0, 0]] * 128
        for k in KEYS:
            sc, ch, sh = (k[0], k[2], k[3]) if which == 1 else (k[1], k[2], k[3])
            if sc < 128:
                t[sc] = [ord(ch) if ch else 0, ord(sh) if sh else 0]
        for name, sc in (('esc', 0x01 if which == 1 else 0x76),):
            t[sc] [0] = SPEC[name]
        lines = ["; keymap set %d — [normal, shift] por scancode" % which,
                 "kbd_map_set%d:" % which]
        for base in range(0, 128, 8):
            lines.append("  db " + ",".join("%d,%d" % tuple(t[i]) for i in range(base, base + 8)))
        return "\n".join(lines)
    hdr = ["; keymap.inc — mapas de teclado EnzoOS (gerado por tools/gengfx.py)",
           "; bytes: [normal, shift]; codigos >=0x80 = teclas especiais"]
    lines = [table(1), "", table(2)]
    # tabelas de teclas estendidas (prefixo E0): entradas (sc, codigo)
    for which, ext in ((1, SET1_EXT), (2, SET2_EXT)):
        name = "kbd_ext%d" % which
        ent = ["", "%s:" % name, "  dw %d" % len(ext)]
        for sc in sorted(ext):
            ent.append("  db %d, %d   ; sc 0x%02X -> %s" % (sc, SPEC[ext[sc]], sc, ext[sc]))
        lines.extend(ent)
    return "\n".join(hdr + lines) + "\n"

