# 8x16 glyphs encoded as 16 hex bytes (rows, MSB = left pixel)
# Hand-tuned readable bitmap, original to NovaLinux.

def bits_from_rows(rows):
    out = []
    for row in rows:
        row = (row + "        ")[:8]
        v = 0
        for i, ch in enumerate(row):
            if ch not in " .":
                v |= 1 << (7 - i)
        out.append(v)
    while len(out) < 16:
        out.append(0)
    return out[:16]

# Very small vector-ish descriptions using strings of '#'
GLYPH_ART = {}

def put(ch, art):
    lines = art.split("\n")
    if lines and lines[0] == "":
        lines = lines[1:]
    if lines and lines[-1] == "":
        lines = lines[:-1]
    GLYPH_ART[ord(ch) if isinstance(ch, str) else ch] = bits_from_rows(lines)

# space
put(" ", "\n".join(["        "] * 16))

# Generate a simple but readable font programmatically
def stamp_rect(rows, x, y, w, h):
    for yy in range(y, min(16, y + h)):
        for xx in range(x, min(8, x + w)):
            rows[yy][xx] = 1

def stamp_pix(rows, x, y):
    if 0 <= x < 8 and 0 <= y < 16:
        rows[y][x] = 1

def to_bytes(rows):
    out = []
    for y in range(16):
        v = 0
        for x in range(8):
            if rows[y][x]:
                v |= 1 << (7 - x)
        out.append(v)
    return out

