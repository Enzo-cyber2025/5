#!/usr/bin/env bash
# =============================================================================
# build_iso_real.sh — CONSTRÓI um ISO bootável REAL, compilado neste ambiente.
#
# Este é o caminho que FUNCIONOU. Ele produz um ISO UEFI-bootável com:
#   - kernel Linux (compilado com -O3 -march=goldmont-plus -mtune=goldmont-plus)
#   - initramfs BusyBox embutido no kernel (CONFIG_INITRAMFS_SOURCE)
#   - El Torito EFI boot (sem GRUB/SYSLINUX — evita binários bloqueados)
#
# Escolhe um kernel que embarca os parsers kconfig PRÉ-GERADOS (flex/bison não
# são necessários), contorna a falta de `bc` (wrapper Python) e a relocação
# R_X86_64_PLT32 do binutils 2.40 (patch no relocs.c).
#
# NB: a rede deste sandbox só libera GitHub/PyPI, por isso o kernel é clonado
# do GitHub e as ferramentas GNU (m4/bison/flex/autotools) não são necessárias.
#
# Saída: NOVALINUX/dist/<nome>.iso + .sha256
# =============================================================================
set -e -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJ="$(cd "${HERE}/.." && pwd)"
WORK="${WORK:-/home/user/novabuild}"
SRC="${WORK}/src"
TOOLS="${WORK}/tools"
OUT="${PROJ}/dist"
BUILD_DIR="${WORK}"

KERNEL_TAG="${KERNEL_TAG:-v4.14}"      # LTS que embarca kconfig _shipped
KERNEL_NAME="linux-414"
ISO_NAME="${ISO_NAME:-navelinux-1.0-x86_64-4.14-uefi.iso}"

mkdir -p "${SRC}" "${TOOLS}" "${OUT}"
log(){ echo -e "\n\u001b[1;32m[NovaLinux/iso-real]\u001b[0m $*"; }

# --- 1. obter kernel (GitHub; rede permitida) -------------------------------
if [ ! -d "${SRC}/${KERNEL_NAME}" ]; then
  log "clonando kernel ${KERNEL_TAG}..."
  git clone --depth 1 --branch "${KERNEL_TAG}" --single-branch \
    https://github.com/torvalds/linux "${SRC}/${KERNEL_NAME}"
fi
K="${SRC}/${KERNEL_NAME}"
[ -f "$K/Makefile" ] || { echo "ERRO: kernel ausente"; exit 1; }

# --- 2. resolucao do kconfig: parsers shipping (sem flex/bison) --------------
log "usando parsers kconfig _shipped (presentes em ${KERNEL_TAG})"
ls "${K}/scripts/kconfig/zconf.tab.c_shipped" >/dev/null 2>&1 || {
  echo "ERRO: kernel ${KERNEL_TAG} não embarca zconf.tab.c_shipped"; exit 1; }

# --- 3. wrapper bc (kernel pede bc p/ timeconst.h) --------------------------
cat > "${TOOLS}/bc" <<'EOF'
#!/usr/bin/env python3
import sys,re,subprocess
src=sys.stdin.read()
m=re.search(r'hz\s*=\s*(\d+)', src)
hz=int(m.group(1)) if m else 1000
out=subprocess.check_output(['python3','/tmp/timeconst.py',str(hz)]).decode()
sys.stdout.write(out)
EOF
chmod +x "${TOOLS}/bc"
# emulador de timeconst
cat > /tmp/timeconst.py <<'PYEOF'
import sys
def gcd(a,b):
    while b: a,b=b,a%b
    return a
def fmul(b,n,d): return ((1<<b)*n + d - 1)//d
def fadj(b,n,d):
    d=d//gcd(n,d); return (1<<b)*(d-1)//d
def fmuls(b,n,d):
    s=0
    while True:
        if fmul(s,n,d) >= (1<<(b-1)): return s
        s+=1
def fmt(v): return format(v,'X')
hz=int(float(sys.argv[1])); L=[]
L.append("/* Automatically generated by kernel/time/timeconst.bc */")
L.append("/* Time conversion constants for HZ == %d */"%hz); L.append("")
L.append("#ifndef KERNEL_TIMECONST_H"); L.append("#define KERNEL_TIMECONST_H"); L.append("")
L.append("#include <linux/param.h>"); L.append("#include <linux/types.h>"); L.append("")
L.append("#if HZ != %d"%hz); L.append('#error "include/generated/timeconst.h has the wrong HZ value!"'); L.append("#endif"); L.append("")
if hz<2: L.append("#error Totally bogus HZ value!")
else:
    s=fmuls(32,1000,hz); L.append("#define HZ_TO_MSEC_MUL32\tU64_C(0x%s)"%fmt(fmul(s,1000,hz))); L.append("#define HZ_TO_MSEC_ADJ32\tU64_C(0x%s)"%fmt(fadj(s,1000,hz))); L.append("#define HZ_TO_MSEC_SHR32\t%s"%s)
    s=fmuls(32,hz,1000); L.append("#define MSEC_TO_HZ_MUL32\tU64_C(0x%s)"%fmt(fmul(s,hz,1000))); L.append("#define MSEC_TO_HZ_ADJ32\tU64_C(0x%s)"%fmt(fadj(s,hz,1000))); L.append("#define MSEC_TO_HZ_SHR32\t%s"%s)
    cd=gcd(hz,1000); L.append("#define HZ_TO_MSEC_NUM\t\t%s"%(1000//cd)); L.append("#define HZ_TO_MSEC_DEN\t\t%s"%(hz//cd)); L.append("#define MSEC_TO_HZ_NUM\t\t%s"%(hz//cd)); L.append("#define MSEC_TO_HZ_DEN\t\t%s"%(1000//cd)); L.append("")
    s=fmuls(32,1000000,hz); L.append("#define HZ_TO_USEC_MUL32\tU64_C(0x%s)"%fmt(fmul(s,1000000,hz))); L.append("#define HZ_TO_USEC_ADJ32\tU64_C(0x%s)"%fmt(fadj(s,1000000,hz))); L.append("#define HZ_TO_USEC_SHR32\t%s"%s)
    s=fmuls(32,hz,1000000); L.append("#define USEC_TO_HZ_MUL32\tU64_C(0x%s)"%fmt(fmul(s,hz,1000000))); L.append("#define USEC_TO_HZ_ADJ32\tU64_C(0x%s)"%fmt(fadj(s,hz,1000000))); L.append("#define USEC_TO_HZ_SHR32\t%s"%s)
    cd=gcd(hz,1000000); L.append("#define HZ_TO_USEC_NUM\t\t%s"%(1000000//cd)); L.append("#define HZ_TO_USEC_DEN\t\t%s"%(hz//cd)); L.append("#define USEC_TO_HZ_NUM\t\t%s"%(hz//cd)); L.append("#define USEC_TO_HZ_DEN\t\t%s"%(1000000//cd))
    cd=gcd(hz,1000000000); L.append("#define HZ_TO_NSEC_NUM\t\t%s"%(1000000000//cd)); L.append("#define HZ_TO_NSEC_DEN\t\t%s"%(hz//cd)); L.append("#define NSEC_TO_HZ_NUM\t\t%s"%(hz//cd)); L.append("#define NSEC_TO_HZ_DEN\t\t%s"%(1000000000//cd)); L.append("")
    L.append("#endif /* KERNEL_TIMECONST_H */")
print("\n".join(L))
PYEOF

# --- 4. patch relocs.c (binutils 2.40 emite R_X86_64_PLT32) -----------------
cd "${K}"
python3 - <<'PYEOF'
p="arch/x86/tools/relocs.c"; s=open(p).read()
old="""	case R_X86_64_PC32:
		/*
		 * PC relative relocations don't need to be adjusted unless
		 * referencing a percpu symbol.
		 */
		if (is_percpu_sym(sym, symname))
			add_reloc(&relocs32neg, offset);
		break;

	case R_X86_64_32:"""
new="""	case R_X86_64_PC32:
	case R_X86_64_PLT32:
		/*
		 * PC relative relocations don't need to be adjusted unless
		 * referencing a percpu symbol. PLT32 is emitted by newer
		 * binutils for PC-relative calls and is handled the same.
		 */
		if (is_percpu_sym(sym, symname))
			add_reloc(&relocs32neg, offset);
		break;

	case R_X86_64_32:"""
if old in s:
    open(p,"w").write(s.replace(old,new,1)); print("patch PLT32 OK")
else:
    print("patch ja aplicado ou bloco mudou")
PYEOF

# --- 5. initramfs embutido (BusyBox) ----------------------------------------
log "montando initramfs embutido usr/initramfs"
rm -rf "${K}/usr/initramfs"
mkdir -p "${K}/usr/initramfs/bin" "${K}/usr/initramfs/sbin" "${K}/usr/initramfs/dev" \
         "${K}/usr/initramfs/proc" "${K}/usr/initramfs/sys" "${K}/usr/initramfs/etc" "${K}/usr/initramfs/tmp"
BB=$(command -v busybox || echo /bin/busybox)
cp "${BB}" "${K}/usr/initramfs/bin/busybox"
for a in sh mount umount ls cp cat echo sleep dmesg mkdir ps kill uname poweroff reboot insmod modprobe ip ifconfig switch_root mknod vi; do
  ln -sf busybox "${K}/usr/initramfs/bin/${a}"
done
ln -sf busybox "${K}/usr/initramfs/sbin/init"
cat > "${K}/usr/initramfs/init" <<'EOF'
#!/bin/busybox sh
mount -t proc none /proc
mount -t sysfs none /sys
mount -t devtmpfs devtmpfs /dev 2>/dev/null || { mkdir -m 755 /dev 2>/dev/null; mount -t tmpfs tmpfs /dev; }
echo
echo "=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+="
echo "   NovaLinux — kernel $(uname -r)  (busybox)  BOOT OK"
echo "   hostname: $(cat /etc/hostname 2>/dev/null || echo novastation)"
echo "=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+=+="
echo
echo "NOVALINUX_BOOT_OK"
exec /bin/busybox sh
EOF
chmod +x "${K}/usr/initramfs/init"
echo "novastation" > "${K}/usr/initramfs/etc/hostname"

# --- 6. configuracao do kernel ---------------------------------------------
log "configurando kernel (EFI stub + initramfs embutido + goldmont)"
export ARCH=x86_64 PATH="${TOOLS}:$PATH"
make ARCH=x86_64 x86_64_defconfig >/dev/null
scripts/config --enable CONFIG_EFI --enable CONFIG_EFI_STUB --enable CONFIG_EFI_VARS
scripts/config --enable CONFIG_BLK_DEV_INITRD
scripts/config --set-str CONFIG_INITRAMFS_SOURCE "usr/initramfs"
scripts/config --enable CONFIG_INITRAMFS_COMPRESSION_GZIP
scripts/config --disable CONFIG_STACK_VALIDATION --disable CONFIG_UNWINDER_ORC
scripts/config --enable CONFIG_UNWINDER_FRAME_POINTER
scripts/config --disable CONFIG_MODULE_SIG --disable CONFIG_SYSTEM_TRUSTED_KEYS --disable CONFIG_DEBUG_INFO
scripts/config --disable CONFIG_SECURITY --disable CONFIG_SECURITY_SELINUX
scripts/config --enable CONFIG_SERIAL_8250 --enable CONFIG_SERIAL_8250_CONSOLE
scripts/config --enable CONFIG_FRAMEBUFFER_CONSOLE --enable CONFIG_VT --enable CONFIG_VT_CONSOLE
scripts/config --set-str CONFIG_DEFAULT_HOSTNAME "novastation"
scripts/config --enable CONFIG_CPU_FREQ --enable CONFIG_CPU_FREQ_GOV_SCHEDUTIL --enable CONFIG_CPU_FREQ_DEFAULT_GOV_SCHEDUTIL
make ARCH=x86_64 olddefconfig >/dev/null

# --- 7. build bzImage -------------------------------------------------------
log "compilando bzImage (-O3 -march=goldmont-plus)"
export KCFLAGS="-O3 -pipe -march=goldmont-plus -mtune=goldmont-plus -fno-semantic-interposition"
export KBUILD_BUILD_USER=nova KBUILD_BUILD_HOST=novastation
make ARCH=x86_64 -j"$(nproc)" bzImage
BZ="${K}/arch/x86/boot/bzImage"
[ -f "${BZ}" ] || { echo "ERRO: bzImage não gerado"; exit 1; }
log "bzImage pronto: $(stat -c%s "${BZ}") bytes"

# --- 8. montar ISO UEFI (pycdlib + El Torito EFI) ---------------------------
log "montando ISO UEFI"
python3 -m pip install --break-system-packages pycdlib >/dev/null 2>&1 || python3 -m pip install pycdlib >/dev/null 2>&1
cp "${HERE}/tools/mkfat.py" "${BUILD_DIR}/mkfat.py"
cp "${HERE}/tools/mkisouefi.py" "${BUILD_DIR}/mkisouefi.py"
cd "${BUILD_DIR}"
python3 mkfat.py "${BZ}"          # gera efi.img (FAT12 com BOOTX64.EFI)
python3 mkisouefi.py "${BZ}" "${OUT}/${ISO_NAME}" efi.img
cd "${OUT}"
sha256sum "${ISO_NAME}" > "${ISO_NAME}.sha256"
log "===== ISO PRONTO ====="
ls -lh "${OUT}/${ISO_NAME}" "${OUT}/${ISO_NAME}.sha256"
echo "ISO_PATH=${OUT}/${ISO_NAME}"
echo "SHA256=$(sed 's| .*||' "${OUT}/${ISO_NAME}.sha256")"
